import json
import threading
from pathlib import Path

from telegram_search.shared.errors import UserError


class ModelTokenizer:
    def __init__(self, bundle: Path):
        from tokenizers import Tokenizer

        self.tokenizer = Tokenizer.from_file(str(bundle / "tokenizer.json"))
        self.tokenizer.no_truncation()
        self.tokenizer.no_padding()
        config = json.loads((bundle / "tokenizer_config.json").read_text())
        pad = config["pad_token"]
        self.pad_id = self.tokenizer.token_to_id(pad if isinstance(pad, str) else pad["content"])
        if self.pad_id is None:
            raise UserError("В закреплённом tokenizer отсутствует padding token.")
        self.lock = threading.RLock()

    def count(self, text: str) -> int:
        with self.lock:
            return len(self.tokenizer.encode(text, add_special_tokens=True).ids)

    def batch(self, texts: list[str], limit: int = 512, *, fixed_length=None, truncate=False):
        with self.lock:
            # Truncation is opt-in for the bounded reranker only. Restore tokenizer
            # state before releasing the lock; chunk counting never truncates.
            if truncate:
                self.tokenizer.enable_truncation(max_length=limit)
            try:
                encodings = self.tokenizer.encode_batch(texts, add_special_tokens=True)
            finally:
                self.tokenizer.no_truncation()
        return self._arrays(encodings, limit, fixed_length)

    def pairs(self, query, documents, *, limit, query_limit, query_characters, document_characters):
        """Bound query first, then truncate only each document in a proper pair.

        Only-second truncation avoids the cross-product of query/document overflow
        windows generated by longest-first on two large inputs. Overflow text is
        never sent for extra inference; truncation is returned to the caller.
        """
        with self.lock:
            bounded = query[:query_characters]
            query_truncated = len(bounded) != len(query)
            encoded = self.tokenizer.encode(bounded, add_special_tokens=False)
            if len(encoded.ids) > query_limit:
                bounded = bounded[: encoded.offsets[query_limit - 1][1]]
                query_truncated = True
            if len(self.tokenizer.encode(bounded, add_special_tokens=False).ids) > query_limit:
                raise UserError("Не удалось ограничить запрос для переранжирования.")
            self.tokenizer.enable_truncation(max_length=limit, strategy="only_second")
            try:
                encodings = self.tokenizer.encode_batch(
                    [(bounded, text[:document_characters]) for text in documents],
                    add_special_tokens=True,
                )
            finally:
                self.tokenizer.no_truncation()
        truncated = [
            bool(item.overflowing) or len(text) > document_characters
            for item, text in zip(encodings, documents, strict=True)
        ]
        return self._arrays(encodings, limit), truncated, query_truncated

    def _arrays(self, encodings, limit, fixed_length=None):
        import numpy as np

        length = max((len(item.ids) for item in encodings), default=0)
        if length > limit:
            raise UserError(
                "Текст превышает лимит модели. Уточните запрос или пересоберите chunks."
            )
        if fixed_length is not None:
            if length > fixed_length or fixed_length > limit:
                raise UserError("Недопустимая длина входа модели.")
            length = fixed_length
        shape = (len(encodings), length)
        ids = np.full(shape, self.pad_id, dtype=np.int64)
        mask = np.zeros(shape, dtype=np.int64)
        types = np.zeros(shape, dtype=np.int64)
        for index, item in enumerate(encodings):
            size = len(item.ids)
            ids[index, :size] = item.ids
            mask[index, :size] = item.attention_mask
            types[index, :size] = item.type_ids
        return {"input_ids": ids, "attention_mask": mask, "token_type_ids": types}
